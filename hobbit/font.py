GW, GH, ADV = 5, 7, 6
_cache = {}


def _glyph(ch, colour, scale):
    key = (ch, colour, scale)
    s = _cache.get(key)
    if s is None:
        rows = _GLYPHS.get(ch, _GLYPHS['?']).split('|')
        s = pygame.Surface((GW * scale, GH * scale), depth=8)
        s.set_palette(P.BASE)
        s.fill(P.TRANSP)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == '#':
                    s.fill(colour, (x * scale, y * scale, scale, scale))
        s.set_colorkey(P.TRANSP)
        _cache[key] = s
    return s


def width(text, scale=1):
    return len(text) * ADV * scale - scale if text else 0


def draw(surf, text, x, y, colour, scale=1, shadow=None):
    text = text.upper()
    if shadow is not None:
        draw(surf, text, x + scale, y + scale, shadow, scale)
    for i, ch in enumerate(text):
        if ch != ' ':
            surf.blit(_glyph(ch, colour, scale), (x + i * ADV * scale, y))


def draw_centered(surf, text, cx, y, colour, scale=1, shadow=None):
    draw(surf, text, cx - width(text.upper(), scale) // 2, y, colour, scale, shadow)


def wrap(text, max_chars):
    words, lines, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > max_chars:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        lines.append(cur)
    return lines
